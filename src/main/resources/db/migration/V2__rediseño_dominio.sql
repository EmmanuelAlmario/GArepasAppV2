-- =============================================================
-- V2 — rediseño del dominio: semántica de unidades, integridad
--      referencial, estado de venta y auditoría de inventario
-- =============================================================
-- Compatible con PostgreSQL y con H2 en modo PostgreSQL (lo usa
-- el test de esquema). No se edita V1: los cambios van en V3, V4...
--
-- 1. Insumos: separar "unidad de presentación" de "unidad base".
--    La columna unidad_medida guardaba la unidad BASE, pero el
--    formulario escribía la base mientras el seeder escribía la de
--    presentación: el mismo campo significaba dos cosas. Ahora
--    unidad_presentacion es lo que elige el usuario y la base es
--    derivada (UnidadMedida.base()).
-- 2. Detalle de receta: la cantidad se guarda siempre en unidad
--    base y la unidad se deriva del insumo. Se elimina la columna
--    redundante (y contradictoria) unidad_medida.
-- 3. Venta: estado ACTIVA/ANULADA. Anular ya no borra la historia.
-- 4. Integridad referencial: las referencias que eran "id suelto"
--    (gastos.produccion_id, producciones.venta_id, ventas.jornada_id)
--    pasan a ser claves foraneas reales.
-- 5. Índices que faltaban en las consultas del sistema.
-- 6. Bitácora de ajustes de inventario (ajustes_inventario).
-- =============================================================

-- ---------- 1. Unidades del insumo ----------
alter table insumos add column unidad_presentacion varchar(20) default 'GRAMO';
update insumos set unidad_presentacion = case
        when unidad_medida in ('CUCHARADA', 'TAZA') then 'GRAMO'
        else unidad_medida
    end;
alter table insumos alter column unidad_presentacion set not null;
alter table insumos alter column unidad_presentacion drop default;
alter table insumos drop column unidad_medida;
alter table insumos add constraint ck_insumos_unidad_presentacion
    check (unidad_presentacion in ('GRAMO', 'KILOGRAMO', 'MILILITRO', 'LITRO', 'UNIDAD'));

-- El precio deja de llamarse "por gramo": es por unidad base (g, ml o u).
alter table insumos rename column precio_por_gramo to precio_unidad_base;
alter table detalle_producciones rename column precio_por_gramo_snapshot to precio_unidad_base_snapshot;

-- ---------- 2. Detalle de receta ----------
alter table detalle_recetas drop column unidad_medida;

-- ---------- 3. Estado de la venta ----------
alter table ventas add column estado varchar(15) default 'ACTIVA';
update ventas set estado = 'ACTIVA' where estado is null;
alter table ventas alter column estado set not null;
alter table ventas alter column estado drop default;
alter table ventas add constraint ck_ventas_estado check (estado in ('ACTIVA', 'ANULADA'));

-- ---------- 4. Integridad referencial ----------
-- Limpieza previa de referencias huerfanas (no habria FK que las proteja).
delete from gastos where produccion_id is not null and produccion_id not in (select id from producciones);
delete from producciones where venta_id is not null and venta_id not in (select id from ventas);
delete from ventas where jornada_id is not null and jornada_id not in (select id from jornadas);

alter table gastos add constraint fk_gastos_produccion
    foreign key (produccion_id) references producciones (id);
alter table producciones add constraint fk_producciones_venta
    foreign key (venta_id) references ventas (id);
alter table ventas add constraint fk_ventas_jornada
    foreign key (jornada_id) references jornadas (id);

-- ---------- 5. Indices faltantes ----------
create index idx_detalle_receta_receta_id on detalle_recetas (receta_id);
create index idx_detalle_receta_insumo_id on detalle_recetas (insumo_id);
create index idx_gastos_produccion_id on gastos (produccion_id);
create index idx_insumos_categoria on insumos (categoria);
create index idx_insumos_activo on insumos (activo);
create index idx_ventas_jornada_id on ventas (jornada_id);
create index idx_ventas_estado on ventas (estado);
create index idx_producciones_producto_id on producciones (producto_id);

-- ---------- 6. Bitacora de ajustes de inventario ----------
create table ajustes_inventario (
    id bigint generated by default as identity primary key,
    insumo_id bigint not null,
    delta numeric(15,4) not null,
    stock_resultante numeric(15,4) not null,
    valor numeric(12,2) not null,
    motivo varchar(150) not null,
    usuario varchar(60) not null,
    fecha timestamp(6) not null,
    constraint fk_ajustes_insumo foreign key (insumo_id) references insumos (id)
);
create index idx_ajustes_insumo_id on ajustes_inventario (insumo_id);
create index idx_ajustes_fecha on ajustes_inventario (fecha);
