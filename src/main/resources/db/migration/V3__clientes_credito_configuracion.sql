







create table clientes (
    id bigint generated by default as identity primary key,
    nombre varchar(80) not null,
    telefono varchar(30),
    direccion varchar(150),
    notas varchar(250),
    activo boolean not null default true,
    creado_en timestamp(6) not null,
    constraint uk_clientes_nombre unique (nombre)
);
create index idx_clientes_activo on clientes (activo);


create table configuracion_negocio (
    id bigint generated by default as identity primary key,
    nombre_comercial varchar(80) not null,
    identificacion_fiscal varchar(40),
    telefono varchar(30),
    direccion varchar(150),
    impuesto_porcentaje numeric(5,2) not null default 0,
    mensaje_recibo varchar(250),
    logo_url varchar(250),
    actualizado_en timestamp(6) not null
);


alter table ventas add column subtotal numeric(12,2) not null default 0;
alter table ventas add column impuestos numeric(12,2) not null default 0;
alter table ventas add column saldo numeric(12,2) not null default 0;
alter table ventas add column forma_pago varchar(20) not null default 'EFECTIVO';
alter table ventas add column fecha_vencimiento timestamp(6);
alter table ventas add column cliente_id bigint;



update ventas set subtotal = total where subtotal = 0 and total <> 0;

alter table ventas add constraint ck_ventas_forma_pago
    check (forma_pago in ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'CREDITO'));
alter table ventas add constraint fk_ventas_cliente
    foreign key (cliente_id) references clientes (id);

create index idx_ventas_cliente_id on ventas (cliente_id);
create index idx_ventas_saldo on ventas (saldo);


create table abonos (
    id bigint generated by default as identity primary key,
    venta_id bigint not null,
    monto numeric(12,2) not null,
    fecha timestamp(6) not null,
    metodo varchar(20) not null,
    nota varchar(150),
    constraint fk_abonos_venta foreign key (venta_id) references ventas (id),
    constraint ck_abonos_metodo
        check (metodo in ('EFECTIVO', 'TARJETA', 'TRANSFERENCIA', 'CREDITO'))
);
create index idx_abonos_venta_id on abonos (venta_id);
create index idx_abonos_fecha on abonos (fecha);


